export function getSuperContent(scenarioId: string): SuperContent | undefined {
  return superContents.find((s) => s.scenarioId === scenarioId);
}

export function getSuperCard(scenarioId: string, cardId: string) {
  return getSuperContent(scenarioId)?.cards.find((c) => c.id === cardId);
}

